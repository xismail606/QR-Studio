export function getInitialLang() {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = localStorage.getItem('qr_language');
    if (saved === 'ar' || saved === 'en') return saved;
    return navigator.language?.startsWith('ar') ? 'ar' : 'en';
  } catch {
    return 'en';
  }
}

export function t(key, lang = 'en', vars = {}) {
  const dict = translations[lang] || translations.en;
  let value = dict[key] || translations.en[key] || key;
  Object.entries(vars).forEach(([name, replacement]) => {
    value = value.replaceAll(`{${name}}`, String(replacement));
  });
  return value;
}

export function localizeValidationError(message, lang = 'en') {
  if (!message || lang === 'en') return message;
  if (message.startsWith('Enter a URL to generate')) return t('validation.emptyUrl', lang);
  if (message.startsWith('That URL looks incomplete')) return t('validation.incompleteUrl', lang);
  if (message.startsWith('Enter a valid URL')) return t('validation.invalidUrl', lang);
  if (message.startsWith('Enter some text')) return t('validation.emptyText', lang);
  if (message.startsWith('Text is too long')) {
    const count = message.match(/\((\d+)\/4000\)/)?.[1] || '';
    return t('validation.longText', lang, { count });
  }
  if (message.startsWith('Unsupported')) return 'نوع الملف غير مدعوم.';
  if (message.includes('too large')) return 'حجم الملف كبير جدًا (الحد الأقصى 2MB).';
  if (message.startsWith('Could not read image')) return 'تعذر قراءة ملف الصورة.';
  return message;
}

export function localizeAuditIssue(issue, lang = 'en') {
  if (lang === 'en') return issue;
  const ratio = issue.message.match(/\(([\d.]+):1\)/)?.[1] || '';
  const keys = {
    'empty-content': ['validation.emptyContent', 'validation.contentFix'],
    'low-contrast': [issue.message.includes('borderline') ? 'audit.borderlineContrast' : 'audit.lowContrast', issue.message.includes('borderline') ? 'audit.borderlineFix' : 'audit.lowContrastFix'],
    'gradient-contrast': ['audit.gradientContrast', 'audit.gradientFix'],
    transparency: ['audit.transparency', 'audit.transparencyFix'],
    'large-logo': [issue.message.includes('Large logo') ? 'audit.largeLogoSmall' : 'audit.largeLogo', issue.message.includes('Large logo') ? 'audit.largeLogoSmallFix' : 'audit.largeLogoFix'],
    'low-ec-with-logo': ['audit.lowEcLogo', 'audit.highEcFix'],
    'small-margin': ['audit.smallMargin', 'audit.marginFix'],
  };
  const [messageKey, fixKey] = keys[issue.code] || [];
  return {
    ...issue,
    message: messageKey ? t(messageKey, lang, { ratio }) : issue.message,
    fix: fixKey ? t(fixKey, lang) : issue.fix,
  };
}

export function setLanguage(lang) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem('qr_language', lang);
  } catch {}
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
  applyDOMTranslations(lang);
}

export function applyDOMTranslations(lang) {
  if (typeof document === 'undefined') return;
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const translated = t(key, lang);
      if (translated) {
        el.textContent = translated;
      }
    }
  });
}
